/**
 * Build a compact skills injection based on video duration and style.
 * Shorter = fewer skills (save tokens). Longer = full injection.
 */
export function buildSkillsInjection(opts: {
  durationMin: number;
  style?: string;
  isWeakModel?: boolean; // true for Flash-Lite or when quality concerns exist
}): string {
  const { durationMin, isWeakModel } = opts;

  // Always inject hook blueprints and transitions (highest ROI)
  let injection = HOOK_BLUEPRINTS + '\n' + TRANSITION_BRIDGES;

  // For videos > 5min, add micro-hooks
  if (durationMin > 5) {
    injection += '\n' + MICRO_HOOKS;
  }

  // For videos > 10min, add emotion wheel
  if (durationMin > 10) {
    injection += '\n' + EMOTION_WHEEL;
  }

  // For videos > 15min or weak models, add sensory details bank
  if (durationMin > 15 || isWeakModel) {
    injection += '\n' + SENSORY_DETAILS;
  }

  // Always add closing formulas
  injection += '\n' + CLOSING_FORMULAS;

  return injection;
}

