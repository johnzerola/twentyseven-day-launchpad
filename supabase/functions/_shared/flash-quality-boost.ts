/**
 * Build the complete quality boost injection based on context.
 * v2.0: Now provides selective boost for ALL tiers, not just Starter.
 */
export function buildFlashQualityBoost(opts: {
  durationMin: number;
  style?: string;
  isStarterTier?: boolean;
  phase?: 'generate' | 'refine';
}): string {
  const { durationMin, isStarterTier, phase } = opts;
  
  let boost = '\n═══ 🚀 QUALITY BOOST ENGINE v2.0 ═══\n';
  
  // Core constraints for ALL tiers (always beneficial)
  boost += FLASH_CONSTRAINTS;
  boost += SHOW_DONT_TELL_PATTERNS;
  
  if (phase === 'generate') {
    boost += FEW_SHOT_HOOKS_PT;
    if (durationMin >= 10) boost += NARRATIVE_SCAFFOLD_TEMPLATE;
  }
  
  if (phase === 'refine') {
    boost += TONAL_VARIATION_RULES;
    boost += EMOTIONAL_DEPTH_TECHNIQUES;
  }
  
  // Starter tier: FULL injection (compensate for weaker models)
  if (isStarterTier) {
    boost += PACING_METRONOME;
  }
  // Pro/Studio: add pacing only for long videos
  else if (durationMin >= 20) {
    boost += PACING_METRONOME;
  }
  
  boost += '\n═══ FIM DO QUALITY BOOST ═══\n';
  return boost;
}

